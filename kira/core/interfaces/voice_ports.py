"""Toolkit-neutral Voice device contracts consumed by the application layer."""
from __future__ import annotations

from typing import Any, Callable, Protocol


class VoiceListenerPort(Protocol):
    """Lifecycle and event contract for one microphone listener."""

    def subscribe(self, event: str, callback: Callable[..., Any]) -> Callable[[], Any] | None: ...
    def start(self) -> Any: ...
    def stop(self) -> Any: ...
    def is_running(self) -> bool: ...
    def begin_speaking(self) -> Any: ...
    def end_speaking(self) -> Any: ...
    def set_muted(self, muted: bool) -> Any: ...


class SpeakerPort(Protocol):
    """Speech output contract independent of any concrete audio/UI toolkit."""

    settings: dict[str, Any]

    def speak(self, text: str, rate=None, pitch=None, cache: bool = False) -> Any: ...
    def stop(self) -> Any: ...
    def stream_reset(self) -> Any: ...
    def stream_text(self, text: str, final: bool = False) -> Any: ...
    def stream_end(self) -> Any: ...
    def play_file(self, path: str) -> Any: ...
    def is_speaking(self) -> bool: ...
