"""Core contracts for Brain planning and post-response Reflection."""
from __future__ import annotations
from typing import Any, Protocol

class BrainService(Protocol):
    """Application-facing contract for per-turn cognitive planning."""
    def decide(self, text: str, mode: Any = None, plan: Any = None, has_attachment: bool = False, has_task: bool = False, settings: Any = None) -> Any: ...
    def default_decision(self) -> Any: ...
    def reset_state(self, character_id: str | None = None) -> None: ...
    def extend_prompt(self, prompt: str, decision: Any, settings: Any = None, router: Any = None, *, character_id: str | None = None) -> str: ...

class ReflectionService(Protocol):
    """Application-facing contract for review of a completed assistant turn."""
    def after_turn(self, router: Any, settings: Any, decision: Any, user_text: str, reply: str, tools: Any = None, mode_name: str | None = None, tool_expected: bool = False, *, character_id: str | None = None) -> dict: ...
