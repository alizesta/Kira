"""Contract consumed by UI/chat; implementation is supplied by Voice module."""
from __future__ import annotations

from typing import Any, Protocol


class VoiceService(Protocol):
    """Application-facing speech and microphone lifecycle contract."""

    def start_recording(self) -> None: ...

    def stop_recording(self) -> None: ...

    def speak(self, text: str, rate: int | None = None, pitch: int | None = None, cache: bool = False) -> None: ...

    def stop_speaking(self) -> None: ...

    def stream_reset(self) -> None: ...

    def stream_text(self, text: str, final: bool = False) -> None: ...

    def stream_end(self) -> None: ...

    def play_file(self, path: str) -> None: ...

    def is_speaking(self) -> bool: ...

    @property
    def settings(self) -> Any: ...

    @settings.setter
    def settings(self, value: Any) -> None: ...

    def begin_speaking(self) -> None: ...

    def end_speaking(self) -> None: ...

    def unmute_if_idle(self) -> None: ...

    def stop_all(self) -> None: ...
