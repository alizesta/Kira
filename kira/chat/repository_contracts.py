"""Application-facing persistence capability contracts."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Callable, Protocol, runtime_checkable


@runtime_checkable
class ConversationRepository(Protocol):
    def create_conversation(self, character_id=None, title="", metadata=None, conversation_id=None) -> dict[str, Any]: ...
    def get_or_create_conversation(self, character_id=None) -> dict[str, Any]: ...
    def get_conversation(self, conversation_id: str) -> dict[str, Any] | None: ...
    def list_conversations(self, character_id=None) -> list[dict[str, Any]]: ...
    def update_conversation(self, conversation_id: str, *, title=None, metadata=None, status=None) -> bool: ...
    def close_conversation(self, conversation_id: str) -> bool: ...
    def delete_conversation(self, conversation_id: str, *, expected_status: str | None = None) -> int: ...
    def update_conversation_lifecycle(self, changes: list[dict[str, Any]]) -> bool: ...
    def mutate_conversations(self, mutations: list[tuple[str, Callable]]) -> dict[str, dict[str, Any]]: ...
    def mutate_all_conversations(self, character_id: str | None, mutator: Callable) -> dict[str, dict[str, Any]]: ...


@runtime_checkable
class MessageRepository(Protocol):
    def add_message(self, role: str, content: str, character_id: str | None = None, **options) -> bool: ...
    def update_stream_message(self, message_id: int, content: str, **options) -> bool: ...
    def conversation_context(self, limit=12, max_chars=12000, character_id=None, conversation_id=None) -> list[dict[str, str]]: ...
    def recent_messages(self, limit=12, character_id=None, conversation_id=None) -> list[dict[str, str]]: ...
    def recent_message_records(self, limit=2000, character_id=None) -> list[dict[str, Any]]: ...
    def get_messages(self, limit=1000, character_id=None, conversation_id=None, after_id=0) -> list[dict[str, Any]]: ...
    def get_transfer_messages(self, conversation_id, character_id, after_created_at="", after_id=0, limit=1000) -> list[dict[str, Any]]: ...
    def message_id_for(self, role, content, character_id=None) -> int | None: ...
    def rows_with_ids(self, limit=3000, after_id=0, character_id=None) -> list[tuple[int, str, str, str]]: ...
    def max_message_id(self) -> int: ...
    def message_count(self, character_id=None, conversation_id=None) -> int: ...
    def pending_count(self) -> int: ...


@runtime_checkable
class HistoryMaintenanceRepository(Protocol):
    def list_snapshots(self, kind="cleared") -> list[Path]: ...
    def clear_memory(self, character_id=None) -> None: ...
    def restore_last_cleared(self) -> int: ...
    def import_messages(self, source: str | Path) -> int: ...
    def import_transfer_records(self, conversations, messages) -> dict[str, Any]: ...


@runtime_checkable
class ChatRepository(ConversationRepository, MessageRepository, HistoryMaintenanceRepository, Protocol):
    @property
    def last_error(self) -> str | None: ...
    @last_error.setter
    def last_error(self, value: str | None) -> None: ...
    def init_db(self) -> list[str]: ...
